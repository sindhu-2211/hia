import re
from datetime import datetime
from fpdf import FPDF


def _strip_markdown(text: str) -> str:
    """Remove markdown markers and sanitize to latin-1 safe chars."""
    text = re.sub(r"\*\*(.*?)\*\*", r"\1", text)
    text = re.sub(r"\*(.*?)\*", r"\1", text)
    text = re.sub(r"#{1,6}\s*", "", text)
    text = re.sub(r"`{1,3}(.*?)`{1,3}", r"\1", text, flags=re.DOTALL)
    text = re.sub(r"^\s*[-•’>]\s*", "  - ", text, flags=re.MULTILINE)
    # Replace common unicode punctuation with ASCII equivalents
    text = text.replace("—", "--").replace("–", "-").replace("‘", "'").replace("’", "'").replace("“", '"').replace("”", '"')
    # Drop any remaining non-latin-1 chars
    text = text.encode("latin-1", errors="replace").decode("latin-1")
    return text.strip()


def _safe(text: str) -> str:
    """Make a string safe for fpdf core fonts (latin-1)."""
    text = text.replace("—", "--").replace("–", "-").replace("‘", "'").replace("’", "'").replace("“", '"').replace("”", '"')
    return text.encode("latin-1", errors="replace").decode("latin-1")


class _PDF(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 14)
        self.set_text_color(26, 35, 126)   # dark blue
        self.cell(0, 10, "Health Insights Agent - Analysis Report", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(26, 35, 126)
        self.set_line_width(0.5)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(3)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f"Generated by HIA on {datetime.now().strftime('%d %b %Y %H:%M')}  |  Page {self.page_no()}", align="C")


def _section_title(pdf: _PDF, title: str):
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_fill_color(232, 234, 246)
    pdf.set_text_color(26, 35, 126)
    w = pdf.w - pdf.l_margin - pdf.r_margin
    pdf.set_x(pdf.l_margin)
    pdf.cell(w, 8, _safe(title), fill=True, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(1)
    pdf.set_text_color(30, 30, 30)


def _body_text(pdf: _PDF, text: str):
    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(30, 30, 30)
    w = pdf.w - pdf.l_margin - pdf.r_margin
    for line in text.splitlines():
        if line.strip():
            pdf.set_x(pdf.l_margin)
            pdf.multi_cell(w, 5, _safe(line))
        else:
            pdf.ln(2)
    pdf.ln(3)


def generate_pdf(patient_name: str, messages: list, biomarkers: list | None = None) -> bytes:
    """
    Build a PDF from session messages and optional biomarker list.
    Returns raw PDF bytes suitable for st.download_button.
    """
    pdf = _PDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # Meta block
    pdf.set_font("Helvetica", size=10)
    pdf.set_text_color(60, 60, 60)
    pdf.cell(0, 6, _safe(f"Patient: {patient_name or 'N/A'}    |    Date: {datetime.now().strftime('%d %b %Y')}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(200, 200, 200)
    pdf.line(10, pdf.get_y(), 200, pdf.get_y())
    pdf.ln(4)

    # Biomarker table
    if biomarkers:
        _section_title(pdf, "Biomarker Summary")
        col_widths = [60, 25, 20, 45, 30]
        headers = ["Biomarker", "Value", "Unit", "Reference Range", "Status"]
        STATUS_COLOR = {
            "normal": (46, 125, 50),
            "low": (21, 101, 192),
            "high": (230, 81, 0),
            "critical_low": (183, 28, 28),
            "critical_high": (183, 28, 28),
            "unknown": (80, 80, 80),
        }
        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(26, 35, 126)
        pdf.set_text_color(255, 255, 255)
        for w, h in zip(col_widths, headers):
            pdf.cell(w, 7, h, border=1, fill=True)
        pdf.ln()
        pdf.set_font("Helvetica", size=8)
        for bm in biomarkers:
            status = bm.get("status", "unknown").lower()
            r, g, b = STATUS_COLOR.get(status, (80, 80, 80))
            # alternate row fill
            pdf.set_fill_color(245, 245, 245)
            pdf.set_text_color(30, 30, 30)
            pdf.cell(col_widths[0], 6, _safe(bm.get("name", "")[:28]), border=1, fill=True)
            pdf.cell(col_widths[1], 6, _safe(bm.get("value", "")), border=1, fill=True, align="C")
            pdf.cell(col_widths[2], 6, _safe(bm.get("unit", "")), border=1, fill=True, align="C")
            pdf.cell(col_widths[3], 6, _safe(bm.get("reference_range", "")[:22]), border=1, fill=True, align="C")
            pdf.set_text_color(r, g, b)
            pdf.cell(col_widths[4], 6, _safe(status.replace("_", " ").title()), border=1, fill=True, align="C")
            pdf.set_text_color(30, 30, 30)
            pdf.ln()
        pdf.ln(4)

    # Analysis + chat
    analysis_done = False
    chat_pairs = []
    for msg in messages:
        role = msg.get("role", "")
        content = msg.get("content", "")
        if role == "system":
            continue
        if role == "assistant" and not analysis_done:
            _section_title(pdf, "AI Analysis")
            _body_text(pdf, _strip_markdown(content))
            analysis_done = True
        elif role == "user" and analysis_done:
            chat_pairs.append(("user", content))
        elif role == "assistant" and analysis_done:
            chat_pairs.append(("assistant", content))

    if chat_pairs:
        _section_title(pdf, "Follow-up Chat")
        w = pdf.w - pdf.l_margin - pdf.r_margin
        for role, content in chat_pairs:
            pdf.set_x(pdf.l_margin)
            if role == "user":
                pdf.set_font("Helvetica", "B", 9)
                pdf.set_text_color(26, 35, 126)
                pdf.multi_cell(w, 5, _safe(f"Q: {content}"))
            else:
                pdf.set_font("Helvetica", size=9)
                pdf.set_text_color(30, 30, 30)
                pdf.multi_cell(w, 5, _strip_markdown(content))
            pdf.ln(2)

    # Disclaimer
    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(150, 150, 150)
    w = pdf.w - pdf.l_margin - pdf.r_margin
    pdf.set_x(pdf.l_margin)
    pdf.multi_cell(w, 4, "Disclaimer: This report is AI-generated and not a substitute for professional medical advice. Consult a qualified healthcare provider for diagnosis and treatment.")

    return bytes(pdf.output())
